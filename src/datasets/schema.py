"""StereoSample and Calibration dataclasses — the canonical per-sample schema.

Every loader must yield instances of ``StereoSample``.  Fields that are
unavailable for a given dataset/split are set to ``None`` (never fabricated).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal, Optional, Tuple

import numpy as np


@dataclass(frozen=True)
class Calibration:
    """Camera calibration for a rectified stereo rig.

    Attributes:
        f_px:        Focal length of the reference (left) camera **in pixels**.
        baseline_m:  Stereo baseline **in metres** (always positive).
    """

    f_px: float
    baseline_m: float

    # ------------------------------------------------------------------ #
    # Depth conversion
    # ------------------------------------------------------------------ #
    def disp_to_depth(self, disp: np.ndarray) -> np.ndarray:
        """Convert disparity (pixels) → metric depth (metres).

        .. math::
            Z = \\frac{f_{\\text{px}} \\cdot B_{\\text{m}}}{d}

        Invalid / zero / negative disparity values produce ``np.inf``.
        """
        safe = np.where(
            np.isfinite(disp) & (disp > 0),
            disp,
            np.inf,  # sentinel → depth becomes 0 after division
        )
        depth = (self.f_px * self.baseline_m) / safe
        return depth.astype(np.float32)

    def __repr__(self) -> str:
        return (
            f"Calibration(f_px={self.f_px:.2f}, "
            f"baseline_m={self.baseline_m:.6f})"
        )


# Provenance tag for the foreground mask.
FgMaskProvenance = Literal[
    "semantic_gt",       # ground-truth semantic labels (e.g. KITTI obj_map)
    "pretrained_seg",    # generated by a pre-trained segmentation model
    "geometric_proxy",   # median-disparity threshold or similar heuristic
    "unavailable",       # no mask of any kind is present
]


@dataclass
class StereoSample:
    """One stereo pair with all available metadata.

    All image arrays are stored as **numpy uint8** with shape ``(H, W, C)``
    (3-channel RGB or replicated grayscale).

    ``gt_disparity``, ``valid_mask``, ``fg_mask`` are ``None`` when the
    underlying dataset does not provide that annotation.
    """

    # ---- Identification ----
    dataset_name: str          # e.g. "kitti2015", "eth3d", "custom"
    split: str                 # e.g. "val_tune", "eval_test", "test_visual"
    scene_id: str              # e.g. "000042", "delivery_area_1l"

    # ---- Images ----
    left_img: np.ndarray       # (H, W, 3) uint8, RGB
    right_img: np.ndarray      # (H, W, 3) uint8, RGB
    left_img_path: str         # absolute path to left image file
    right_img_path: str        # absolute path to right image file
    img_size: Tuple[int, int]  # (H, W)

    # ---- Ground-truth disparity ----
    gt_disparity: Optional[np.ndarray] = None   # float32, pixels
    valid_mask: Optional[np.ndarray] = None      # bool, True where GT is valid

    # ---- Foreground mask ----
    fg_mask: Optional[np.ndarray] = None         # bool, True for foreground
    fg_mask_provenance: FgMaskProvenance = "unavailable"

    # ---- Calibration ----
    calib: Optional[Calibration] = None

    # ------------------------------------------------------------------ #
    # Convenience helpers
    # ------------------------------------------------------------------ #
    @property
    def has_gt(self) -> bool:
        return self.gt_disparity is not None

    @property
    def has_calib(self) -> bool:
        return self.calib is not None

    @property
    def left(self) -> np.ndarray:
        return self.left_img

    @property
    def right(self) -> np.ndarray:
        return self.right_img

    @property
    def gt_disp(self) -> Optional[np.ndarray]:
        return self.gt_disparity

    @property
    def dataset(self) -> str:
        return self.dataset_name

    def summary(self) -> str:
        """One-line human-readable summary."""
        gt = "GT" if self.has_gt else "no-GT"
        cal = f"f={self.calib.f_px:.1f} B={self.calib.baseline_m:.4f}" if self.has_calib else "no-calib"
        fg = self.fg_mask_provenance
        return (
            f"[{self.dataset_name}/{self.split}] {self.scene_id}  "
            f"{self.img_size[1]}×{self.img_size[0]}  {gt}  {cal}  fg={fg}"
        )
